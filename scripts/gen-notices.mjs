#!/usr/bin/env node
// Regenerate packages/sdk/THIRD_PARTY_NOTICES.md from docs/provenance/dependencies.json (NEW-5) and the licence files of
// each production crate in the cargo registry / vendor/. Usage: node scripts/gen-notices.mjs [--check]
// --check exits 1 when the committed file differs. Not legal clearance; see docs/provenance/assets.md.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "packages/sdk/THIRD_PARTY_NOTICES.md");
const deps = JSON.parse(readFileSync(join(root, "docs/provenance/dependencies.json"), "utf8"));
const prod = deps.packages.filter((p) => p.ecosystem === "cargo" && p.kind === "prod").sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const registry = join(homedir(), ".cargo/registry/src");
const regDirs = existsSync(registry) ? readdirSync(registry).map((d) => join(registry, d)) : [];
const crateDir = (p) => {
  if (p.source.startsWith("vendor/")) return join(root, p.source.split(" ")[0]);
  if (p.source.startsWith("workspace")) return null;
  return regDirs.map((d) => join(d, `${p.name}-${p.version}`)).find(existsSync) ?? null;
};
const text = (f) => readFileSync(f, "utf8").replace(/\r\n/g, "\n").trim();
const byText = new Map(); // licence text -> { names: Set, files: Set }
const noFile = [];
for (const p of prod) {
  const dir = crateDir(p);
  if (!dir) { if (!p.source.startsWith("workspace")) noFile.push(`${p.name} ${p.version} (crate source not found)`); continue; }
  const files = readdirSync(dir).filter((f) => /^(LICEN[SC]E|COPYING|NOTICE|UNLICENSE)/i.test(f)).sort();
  if (!files.length) { noFile.push(`${p.name} ${p.version}`); continue; }
  for (const f of files) {
    const t = text(join(dir, f));
    if (!t) continue;
    const e = byText.get(t) ?? { crates: new Set(), files: new Set() };
    e.crates.add(`${p.name} ${p.version}`); e.files.add(f); byText.set(t, e);
  }
}
const asset = (f) => text(join(root, "vendor/hayro-interpret/assets", f));
const lines = [
  "# Third-party notices for @zilijonas/foliark",
  "",
  "PRIVATE, UNRELEASED. Generated by `scripts/gen-notices.mjs` from `docs/provenance/dependencies.json` and the licence files of each crate.",
  "Foliark-authored code is AGPL-3.0-only, copyright 2026 Linas Jonas Zilinskas; separate commercial licensing is described in LICENSING.md and COMMERCIAL-LICENSING.md. Third-party material keeps its own terms. This inventory describes the recorded wasm production graph, not legal clearance.",
  "The package has no runtime npm dependencies.",
  "",
  "## Data embedded in the wasm",
  "",
  "### Standard 14 fonts (Foxit, from PDFium), via hayro-interpret `embed-fonts`",
  "FoxitSans, FoxitSerif, FoxitFixed (regular, bold, italic, bold italic), FoxitSymbol, FoxitDingbats. Licence text, also shipped as `LICENSE_FOXIT`:",
  "",
  "```",
  asset("LICENSE_FOXIT"),
  "```",
  "",
  "### ICC colour profiles (CC0)",
  "`CGATS001Compat-v2-micro.icc`, `LAB.icc` (hayro-interpret, hayro-jpeg2000), `ProPhoto-v2-micro.icc` (hayro-jpeg2000). Notice shipped with the profiles:",
  "",
  "```",
  asset("CGATS_LICENSE.txt"),
  "```",
  "",
  "### Predefined CMap pack (BSD-3-Clause, Adobe), shipped as `cmaps/*.cmap`, not in the wasm",
  "63 CMap resources copied unchanged from adobe-type-tools/cmap-resources and adobe-type-tools/mapping-resources-pdf (pinned commits in `cmaps/MANIFEST.json`). Each file carries its own copyright header; licence text, also shipped as `cmaps/LICENSE.txt`:",
  "",
  "```",
  text(join(root, "packages/sdk/cmaps/LICENSE.txt")),
  "```",
  "",
  `## Rust crates compiled into the wasm (${prod.length}, production graph of foliark-wasm for wasm32-unknown-unknown)`,
  "",
  "| crate | version | licence (SPDX as declared) |",
  "|---|---|---|",
  ...prod.map((p) => `| ${p.name} | ${p.version} | ${p.license}${p.source.startsWith("vendor/") ? " (vendored, patched fork)" : ""} |`),
  "",
  "`foliark-engine`, `foliark-model` and `foliark-wasm` are Foliark-authored code under AGPL-3.0-only, with separate commercial licensing available from the copyright holder.",
  "Crates that offer a choice (`A OR B`) are used under the terms of either option; each licence text below ships with them.",
  "",
  "## Licence texts",
  "Each distinct text found in the crates' source, with the crates that carry it.",
  "",
];
let n = 0;
for (const [t, e] of [...byText].sort((a, b) => [...a[1].crates][0].localeCompare([...b[1].crates][0]))) {
  const id = createHash("sha256").update(t).digest("hex").slice(0, 8);
  lines.push(`### ${++n}. ${[...e.files].join(", ")} (text ${id})`, `Crates: ${[...e.crates].join(", ")}`, "", "```", t, "```", "");
}
if (noFile.length) lines.push("## Crates without a licence file in their source", "Their SPDX expression above is the only statement available here:", ...noFile.map((c) => `- ${c}`), "");
const body = lines.join("\n");
if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== body) { console.error("THIRD_PARTY_NOTICES.md is stale: run node scripts/gen-notices.mjs"); process.exit(1); }
  console.log("notices: up to date");
} else { writeFileSync(out, body); console.log(`wrote ${out}: ${prod.length} crates, ${byText.size} distinct licence texts, ${noFile.length} without a file`); }
